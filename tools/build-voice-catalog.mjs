/* Build deterministic recordings from the game's existing Traditional-Chinese copy. */
import {createRequire} from 'node:module';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import vm from 'node:vm';
const require=createRequire(import.meta.url),base=new URL('../',import.meta.url);
const html=await readFile(new URL('index.html',base),'utf8');
const clean=s=>String(s).replace(/[\p{Extended_Pictographic}\uFE0F\u200D]/gu,'').replace(/\s+/g,' ').trim();
const entries=new Map(),counts={};
function add(text,category){
  text=clean(text);if(!/[\u4e00-\u9fff]/.test(text)||/[<>]/.test(text))return;
  // Keep individual recordings short, but split only at punctuation, never mid-word.
  const sentences=text.match(/[^。！？!?；;]+[。！？!?；;]?/g)||[text];let chunk='';
  const put=t=>{if(!entries.has(t)){entries.set(t,category);counts[category]=(counts[category]||0)+1;}};
  for(const s of sentences){if(chunk.length+s.length>145&&chunk){put(chunk);chunk='';}chunk+=s;}if(chunk)put(chunk);
}
function walk(value,category){if(typeof value==='string')add(value,category);else if(value&&typeof value==='object')Object.values(value).forEach(v=>walk(v,category));}
const N=require('../story/tower-narrative.js'),S=require('../story/tower-side-stories.js'),D=require('../story/tower-dungeons.js'),C=require('../story/story-core.js');
for(const text of ['歡迎來到移動迷宮。請選擇你的冒險。','你好，我會陪你探索迷宮。準備好了，就一起出發吧！','劇情模式・倒轉高塔','單人遊戲','多人遊戲','遊戲設定','勇者歷史','遊戲說明','經典闖關','尋寶對戰','鬼抓人','搶購模式','合作奪旗','第三人稱','第一人稱','俯視視角','恭喜過關！','遊戲結束','準備完成','準備出發','出發！','下一頁','上一頁','回到迷宮','回到首頁','故事日誌','背包','裝備與補給','繼續遊戲','對話','任務完成','結帳完成','蒐集任務完成，獲得三百分','受到攻擊','受到攻擊，裝備已損壞','待找','車上','已結帳','鐵鍬已滿'])add(text,'interface');
const names=new Set();
for(const name of ['ITEM_TYPES','FOOD_TYPES','GOODS','ENV_ITEMS']){
  const part=html.match(new RegExp('const '+name+'=([\\s\\S]*?)\\n[\\]}];'))?.[0]||'';
  for(const m of part.matchAll(/name:\s*'([^']+)'/g))names.add(m[1]);
}
for(const entry of [...Object.values(C.ITEMS),...Object.values(C.GEAR)])names.add(entry.name);
for(const name of ['加速','油漬','黏鼠板','泡沫','雞蛋'])names.add(name);
for(const name of names){add('獲得 '+name,'pickup');add(name,'item-name');}
for(const name of [...Object.values(C.ITEMS).map(x=>x.name),'加速','油漬','黏鼠板','泡沫','雞蛋','鐵鍬','大風箏','集合口哨','加速藥水','強力加速藥水','穿牆斗篷','魔法地圖','指南針','時間寶石','幸運星','調皮鬼','城堡魔法鑰匙','超亮探照燈','貓頭鷹視野','驅霧號角','火山震波'])add('使用 '+name,'use');
for(const item of Object.values(C.GEAR))add('裝備 '+item.name,'equipment');
for(const item of [...Object.values(C.GEAR),...Object.values(C.ITEMS)])add('賣出 '+item.name,'trade');
for(const file of ['index.html','assets/shop-chaos.js','assets/tag-rage.js','assets/capture-mode.js','story/tower-mode.js']){
  const source=await readFile(new URL(file,base),'utf8');
  for(const m of source.matchAll(/(?:showToast|action)\(\s*('(?:[^'\\]|\\.)*')(?=\s*[,\)])/g))add(vm.runInNewContext(m[1]),'event');
}
for(const text of ['哎呀！踩到油漬，方向亂掉了！','踩到黏鼠板，走不動了！','滿地泡泡！腳步變得慢吞吞！','踩到加速踏板，咻！衝出去囉！','哎呀！雞蛋糊到臉上了！'])add(text,'trap');
walk(N.CHAPTERS,'main-story');walk(N.SCENES,'main-story');walk(N.ENDINGS,'ending');walk(S.STORIES,'side-story');walk(D.TYPES,'dungeon');
// Stable content IDs let interrupted generation reuse completed recordings.
for(const name of ['CHARS','LEVELS']){
  const part=html.match(new RegExp('const '+name+'=\\[([\\s\\S]*?)\\n\\];'))?.[1]||'';
  for(const m of part.matchAll(name==='CHARS'?/job:'([^']+)'/g:/name:'([^']+)'/g))add(m[1],'selection');
}
add('俯視','selection');
const tower=await readFile(new URL('story/tower-mode.js',base),'utf8');
const fragments=tower.match(/const fragments=(\{[^\n]+\});/)?.[1];
if(fragments)walk(vm.runInNewContext('('+fragments+')'),'dungeon-story');
for(const text of ['比賽搶終點','尋寶','搶購'])add(text,'selection');
const rows=[...entries].map(([text,category])=>({id:'generated.'+createHash('sha256').update(text).digest('hex').slice(0,16),text,category}));
const content='/* Generated by tools/build-voice-catalog.mjs from game copy. No audio preloading. */\n(function(root){\n  const rows='+JSON.stringify(rows,null,2)+';\n  const tracks=Object.fromEntries(rows.map(r=>[r.id,Object.freeze({text:r.text,category:r.category,src:"./assets/voice/generated/"+r.id.slice(10)+".mp3"})]));\n  const api=Object.freeze({tracks:Object.freeze(tracks)});\n  if(typeof module==="object"&&module.exports)module.exports=api;\n  if(root)root.MazeVoiceCatalog=api;\n})(typeof globalThis!=="undefined"?globalThis:this);\n';
await writeFile(new URL('assets/voice-catalog.js',base),content);
console.log(JSON.stringify({clips:rows.length,characters:rows.reduce((n,r)=>n+r.text.length,0),categories:counts},null,2));
